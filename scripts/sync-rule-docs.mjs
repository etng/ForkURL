function upsertIndexRulesSection (groups) {
  const index = fs.readFileSync(indexPath, 'utf8')
  const generated = renderRulesSection(groups)
  if (index.includes(INDEX_START) && index.includes(INDEX_END)) {
    const pattern = new RegExp(`${escapeRegExp(INDEX_START)}[\\s\\S]*?${escapeRegExp(INDEX_END)}`)
    fs.writeFileSync(indexPath, index.replace(pattern, generated), 'utf8')
    return
  }

  const anchor = '\n\t\t\t<section class="workflow-section">'
  if (!index.includes(anchor)) {
    throw new Error('Could not find workflow section insertion point in site/index.html')
  }
  fs.writeFileSync(indexPath, index.replace(anchor, `\n${generated}\n${anchor.trimStart()}`), 'utf8')
}

function main () {
  const rules = readRules()
  const groups = documentedGroups(rules)
  fs.mkdirSync(path.dirname(docsPath), { recursive: true })
  fs.writeFileSync(docsPath, renderDocsMarkdown(groups), 'utf8')
  upsertReadmeBlock(groups)
  upsertIndexRulesSection(groups)
  const stats = statsFor(groups)
  console.log(`wrote README.md, docs/default-rules.md, site/index.html#rules (${stats.groupCount} groups, ${stats.ruleCount} rules, ${stats.linkCount} links)`)
}

main()
