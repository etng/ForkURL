#!/usr/bin/env node
// Regenerate user-facing default-rule documentation from rules.json.
//
// This keeps the website, README and docs snapshot aligned whenever a rule
// submission is merged into rules.json.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rulesPath = path.join(rootDir, 'rules.json')
const readmePath = path.join(rootDir, 'README.md')
const docsPath = path.join(rootDir, 'docs/default-rules.md')
const indexPath = path.join(rootDir, 'site/index.html')

const README_START = '<!-- DEFAULT_RULES_TABLE_START -->'
const README_END = '<!-- DEFAULT_RULES_TABLE_END -->'
const INDEX_START = '<!-- DEFAULT_RULES_SECTION_START -->'
const INDEX_END = '<!-- DEFAULT_RULES_SECTION_END -->'

